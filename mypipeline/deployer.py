def run_demo():
    print("\n" + "="*55)
    print("  Phase 6 — Deployer Demo")
    print("="*55)

    deployer = Deployer(marketplace_dir="marketplace")
    summary  = deployer.deploy()

    print(f"\n  Status       : {summary['status']}")
    if summary["status"] == "ready":
        print(f"  APIs ready   : {summary['api_count']}")
        print(f"  Categories   : {summary['category_count']}")
        print(f"  Total size   : {summary['total_size_kb']} KB")
        print(f"  Warnings     : {summary['warnings']}")
        print(f"\n  GitHub Pages endpoints:")
        print(f"    Index    : /index.json")
        print(f"    API      : /apis/{{api_id}}.json")
        print(f"    Category : /categories/{{category}}.json")
        print(f"    Search   : /search/index.json")
        print(f"    Manifest : /manifest.json")

        # Show manifest
        if Path("marketplace/manifest.json").exists():
            manifest = json.loads(
                Path("marketplace/manifest.json").read_text(encoding="utf-8")
            )
            print(f"\n  Deployment manifest:")
            print(f"    Deployed at : {manifest['deployed_at']}")
            print(f"    APIs        : {manifest['api_count']}")
            print(f"    Endpoints   : {manifest['endpoint_count']}")
            print(f"    Categories  : {manifest['category_counts']}")
    else:
        print(f"  Reason: {summary.get('reason', 'unknown')}")

    print("\n" + "="*55)
    print("  Phase 6 complete")
    print("="*55)


if __name__ == "__main__":
    run_demo()
