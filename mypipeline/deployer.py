# Main Deployer
# ─────────────────────────────────────────────────────────────

class Deployer:
    """
    Phase 6 — Prepares and verifies GitHub Pages deployment.

    GitHub Actions then commits the marketplace/ directory
    and GitHub Pages serves it automatically.

    No zip. No GitHub release assets. Just static files.
    """

    def __init__(self, marketplace_dir: str = "marketplace"):
        self.marketplace_dir = Path(marketplace_dir)

    def deploy(self) -> dict:
        logger.info("=" * 50)
        logger.info("Phase 6 — Deployer starting")
        logger.info("=" * 50)

        if not self.marketplace_dir.exists():
            logger.error("marketplace/ directory not found")
            return {"status": "failed",
                    "reason": "marketplace directory missing"}

        # Step 1: Pre-deployment verification
        logger.info("Running pre-deployment verification...")
        verifier = PreDeploymentVerifier()
        verify_results = verifier.verify(self.marketplace_dir)

        if not verify_results["passed"]:
            for error in verify_results["errors"]:
                logger.error(f"Verification error: {error}")
            return {
                "status": "failed",
                "reason": "pre-deployment verification failed",
                "errors": verify_results["errors"]
            }

        for warning in verify_results["warnings"]:
            logger.warning(f"Verification warning: {warning}")

        # Step 2: Generate .nojekyll — CRITICAL for GitHub Pages
        # Without this, GitHub Pages runs Jekyll which:
        #   - Silently drops files/dirs starting with _ (_config.yml, _headers)
        #   - May not serve .json files with correct Content-Type
        #   - Makes the entire marketplace inaccessible to Flutter
        nojekyll_path = self.marketplace_dir / ".nojekyll"
        nojekyll_path.write_text("")
        logger.debug("Generated .nojekyll")

        # Step 3: Generate GitHub Pages config
        config_path = self.marketplace_dir / "_config.yml"
        config_path.write_text(generate_github_pages_config())
        logger.debug("Generated _config.yml")

        # Step 4: Generate headers file
        headers_path = self.marketplace_dir / "_headers"
        headers_path.write_text(generate_headers_file())
        logger.debug("Generated _headers")

        # Step 5: Generate deployment manifest
        manifest = generate_deploy_manifest(
            self.marketplace_dir, verify_results
        )

        # Save manifest to logs
        DEPLOY_MANIFEST.parent.mkdir(parents=True, exist_ok=True)
        DEPLOY_MANIFEST.write_text(json.dumps(manifest, indent=2))

        # Also save manifest inside marketplace for Flutter to fetch
        marketplace_manifest = self.marketplace_dir / "manifest.json"
        marketplace_manifest.write_text(json.dumps(manifest, indent=2))

        summary = {
            "status"         : "ready",
            "api_count"      : verify_results["file_counts"].get("api_files", 0),
            "category_count" : verify_results["file_counts"].get("category_files", 0),
            "total_size_kb"  : round(verify_results.get("total_size_kb", 0), 2),
            "warnings"       : len(verify_results["warnings"]),
            "github_pages_url": manifest["github_pages_url"]
        }

        logger.info(
            f"Phase 6 complete: {summary['api_count']} APIs ready, "
            f"{summary['category_count']} categories, "
            f"{summary['total_size_kb']:.1f}KB total"
        )
        logger.info(
            f"GitHub Pages URL: {summary['github_pages_url']}"
        )

        return summary


