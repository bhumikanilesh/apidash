# Constants
# ─────────────────────────────────────────────────────────────

MARKETPLACE_DIR = Path("marketplace")
DEPLOY_MANIFEST = Path("logs/deploy_manifest.json")


# ─────────────────────────────────────────────────────────────
# GitHub Pages Config Generator
# ─────────────────────────────────────────────────────────────

def generate_github_pages_config() -> str:
    """
    Generates _config.yml for GitHub Pages.
    Ensures JSON files are served with correct content type.
    """
    return """# GitHub Pages configuration for API Dash Marketplace
# Auto-generated by API Explorer Pipeline

include:
  - "*.json"

# Disable Jekyll processing — serve files as-is
plugins: []
"""


def generate_headers_file() -> str:
    """
    Generates _headers file for Netlify-style CORS headers.
    For GitHub Pages, CORS is handled differently but this
    documents the required headers for reference.

    Flutter needs:
      Access-Control-Allow-Origin: *
    to fetch JSON files from a different domain.
    """
    return """# CORS Headers for API Dash Explorer
# These headers allow the Flutter app to fetch templates
# from GitHub Pages without CORS errors

/*
  Access-Control-Allow-Origin: *
  Content-Type: application/json
  Cache-Control: public, max-age=3600
"""


# ─────────────────────────────────────────────────────────────
# Pre-deployment Verifier
# Checks all files are valid before marking ready to deploy
# ─────────────────────────────────────────────────────────────

class PreDeploymentVerifier:
    """
    Verifies the marketplace directory is ready for deployment.

    Checks:
      - index.json exists and is valid
      - All api files are valid JSON
      - All category files are valid JSON
      - No empty files
      - File count matches index entries
    """

    def verify(self, marketplace_dir: Path) -> dict:
        results = {
            "passed"        : True,
            "errors"        : [],
            "warnings"      : [],
            "file_counts"   : {},
            "total_size_kb" : 0
        }

        # Check index.json
        index_path = marketplace_dir / "index.json"
        if not index_path.exists():
            results["errors"].append("index.json missing")
            results["passed"] = False
            return results

        try:
            index = json.loads(index_path.read_text(encoding="utf-8"))
            results["file_counts"]["index_entries"] = len(index)
        except json.JSONDecodeError as e:
            results["errors"].append(f"index.json invalid: {e}")
            results["passed"] = False
            return results

        # Check api files
        apis_dir = marketplace_dir / "apis"
        api_files = list(apis_dir.glob("*.json")) if apis_dir.exists() else []
        invalid_apis = []

        for filepath in api_files:
            try:
                content = filepath.read_text(encoding="utf-8")
                if not content.strip():
                    results["warnings"].append(f"Empty file: {filepath.name}")
                    continue
                template = json.loads(content)

                # Verify required fields
                if "info" not in template or "requests" not in template:
                    invalid_apis.append(filepath.name)
                    results["errors"].append(
                        f"{filepath.name} missing required fields"
                    )

                results["total_size_kb"] += len(content) / 1024

            except json.JSONDecodeError:
                invalid_apis.append(filepath.name)
                results["errors"].append(f"{filepath.name} is invalid JSON")

        results["file_counts"]["api_files"] = len(api_files)
        results["file_counts"]["invalid_apis"] = len(invalid_apis)

        # Check category files
        cats_dir = marketplace_dir / "categories"
        cat_files = list(cats_dir.glob("*.json")) if cats_dir.exists() else []
        results["file_counts"]["category_files"] = len(cat_files)

        for filepath in cat_files:
            try:
                json.loads(filepath.read_text(encoding="utf-8"))
            except json.JSONDecodeError:
                results["warnings"].append(
                    f"Invalid category file: {filepath.name}"
                )

        # Check file count matches index
        if len(api_files) != len(index):
            results["warnings"].append(
                f"File count mismatch: {len(api_files)} files "
                f"but {len(index)} index entries"
            )

        if results["errors"]:
            results["passed"] = False

        return results


# ─────────────────────────────────────────────────────────────
# Deployment Manifest Generator
# ─────────────────────────────────────────────────────────────

def generate_deploy_manifest(marketplace_dir: Path,
                             verify_results: dict) -> dict:
    """
    Generates a deployment manifest for auditing and monitoring.
    Saved to logs/deploy_manifest.json after each run.

    Flutter app can fetch this to show "last updated" info.
    """
    index_path = marketplace_dir / "index.json"
    apis_dir   = marketplace_dir / "apis"

    # Count endpoints across all templates
    total_endpoints = 0
    category_counts = {}

    if apis_dir.exists():
        for filepath in apis_dir.glob("*.json"):
            try:
                template = json.loads(filepath.read_text(encoding="utf-8"))
                total_endpoints += len(template.get("requests", []))
            except (json.JSONDecodeError, IOError):
                pass

    # Count by category from index
    if index_path.exists():
        try:
            index = json.loads(index_path.read_text(encoding="utf-8"))
            for entry in index.values():
                for cat in entry.get("categories", []):
                    category_counts[cat] = category_counts.get(cat, 0) + 1
        except (json.JSONDecodeError, IOError):
            pass

    github_pages_url = os.environ.get("GITHUB_PAGES_URL", "").rstrip("/")

    return {
        "deployed_at"    : time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "api_count"      : verify_results["file_counts"].get("api_files", 0),
        "endpoint_count" : total_endpoints,
        "category_counts": category_counts,
        "total_size_kb"  : round(verify_results.get("total_size_kb", 0), 2),
        "verification"   : {
            "passed"  : verify_results["passed"],
            "errors"  : len(verify_results["errors"]),
            "warnings": len(verify_results["warnings"])
        },
        "github_pages_url": github_pages_url,
        "endpoints"      : {
            "index"     : "/index.json",
            "api_detail": "/apis/{api_id}.json",
            "category"  : "/categories/{category}.json",
            "search"    : "/search/index.json"
        }
    }


